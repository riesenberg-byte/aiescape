import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
const types = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.svg': 'image/svg+xml', '.webmanifest': 'application/manifest+json' };
const assets = {};
for (const file of (await readdir(new URL('../public/', import.meta.url))).sort()) {
  const ext = file.slice(file.lastIndexOf('.'));
  if (!types[ext]) throw new Error(`Unsupported public asset ${file}`);
  assets['/' + file] = { type: types[ext], body: await readFile(new URL('../public/' + file, import.meta.url), 'utf8') };
}
await mkdir(new URL('../src/generated/', import.meta.url), { recursive: true });
await writeFile(new URL('../src/generated/assets.js', import.meta.url), `// Generated by npm run build.\nexport const assets = ${JSON.stringify(assets)};\n`);
console.log(`Built ${Object.keys(assets).length} self-contained assets; no external runtime dependencies.`);
